//! Authored venue metadata from the USA MX TrackList.res, UI/Tracks.dat and ATY lists.
//! No multiplayer numbers are assigned. atv-net currently validates only IDs 1..=40.
//! Online support requires appending to MAP_ENVIRONMENTS (preserving 1..=40),
//! updating MAX_MAP_ID/valid_map consumers and client/server compatibility tests.
/// Remains false until the terrain decoder and real-map acceptance checks are integrated.
pub const RUNTIME_SUPPORTED: bool = false;
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct MxCourse {
    pub id: &'static str,
    pub name: &'static str,
    pub group: &'static str,
    pub archive: &'static str,
    pub scene_stem: &'static str,
    pub mode_stem: &'static str,
}
pub fn get(id: &str) -> Option<&'static MxCourse> {
    COURSES.iter().find(|c| c.id == id)
}
/// Runtime support and per-map validation are both required; content presence alone is insufficient.
pub fn available(id: &str, validated: bool) -> bool {
    RUNTIME_SUPPORTED && validated && get(id).is_some()
}
