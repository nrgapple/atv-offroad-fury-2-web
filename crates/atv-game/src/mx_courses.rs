#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn complete_unique_and_gated() {
        assert_eq!(COURSES.len(), 56);
        let mut ids = std::collections::HashSet::new();
        for c in COURSES {
            assert!(ids.insert(c.id));
            assert!(!available(c.id, false));
            assert_eq!(available(c.id, true), RUNTIME_SUPPORTED);
            assert_eq!(c.scene_stem, c.mode_stem);
            assert_eq!(
                c.archive,
                format!("/MX/MAPS/{}.RES", c.scene_stem.to_uppercase())
            );
        }
        assert_eq!(get("mx_nat01").unwrap().scene_stem, "nat01");
        assert!(get("nat01").is_none());
    }
}
